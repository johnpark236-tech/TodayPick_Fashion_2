export function detectCurrentSeason(): Season {
  const month = new Date().getMonth() + 1; // 1-12
  if (month >= 3 && month <= 5) return '봄';
  if (month >= 6 && month <= 8) return '여름';
  if (month >= 9 && month <= 11) return '가을';
  return '겨울';
}

export function getGreetingByTime(): { greeting: string; sub: string } {
  const hour = new Date().getHours();
  if (hour >= 5 && hour < 11) {
    return { greeting: '좋은 아침이에요', sub: '오늘 하루를 기분 좋게 시작할 맞춤 코디를 골라드렸어요' };
  } else if (hour >= 11 && hour < 17) {
    return { greeting: '화창한 오후예요', sub: '오늘의 활동과 날씨에 가장 잘 어울리는 스타일이에요' };
  } else if (hour >= 17 && hour < 22) {
    return { greeting: '편안한 저녁이에요', sub: '퇴근길과 저녁 약속까지 멋스럽게 이어지는 코디예요' };
  } else {
    return { greeting: '차분한 밤 되세요', sub: '내일 아침 고민을 덜어줄 미리 만나는 데일리 룩이에요' };
  }
}

